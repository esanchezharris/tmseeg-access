"""Run the documented SQL examples. Writes docs/catalog_queries.md and results/catalog_queries.json.

Docs are generated, so each example is known to run and its output is real.
"""

from __future__ import annotations

import json
import statistics
import time
from pathlib import Path

from tmseeg_access.catalog import default_path, query
from tmseeg_access.config import resolve_data_root

ROOT = Path(__file__).resolve().parents[1]
REPEATS = 7
CLEAN_RUNS = """
    WITH problem_runs AS (
        SELECT DISTINCT recording_id FROM issues
        WHERE severity = 'error' AND recording_id IS NOT NULL
    )"""
QUERIES = [
    (
        "How many runs does each site have, and how many depart from 120 markers?",
        """SELECT acquisition AS site,
       count(*) AS runs,
       count(*) FILTER (pulse_count <> 120) AS runs_not_120
FROM recordings
WHERE task = 'tmseeg'
GROUP BY site
ORDER BY site""",
    ),
    (
        "Which subjects are missing a TMS run?",
        """SELECT p.subject,
       count(r.recording_id) AS tms_runs
FROM participants p
LEFT JOIN recordings r ON r.subject = p.subject AND r.task = 'tmseeg'
GROUP BY p.subject
HAVING tms_runs < 4
ORDER BY tms_runs, p.subject""",
    ),
    (
        "Which runs have the most suspected duplicate markers?",
        """SELECT recording_id,
       count(*) AS markers,
       sum(is_duplicate::INT) AS duplicates
FROM pulses
GROUP BY recording_id
ORDER BY duplicates DESC
LIMIT 5""",
    ),
    (
        "What is the longest gap between pulses in each of the worst runs?",
        """SELECT recording_id,
       round(max(gap_from_previous_s), 2) AS longest_gap_s
FROM pulses
GROUP BY recording_id
ORDER BY longest_gap_s DESC
LIMIT 5""",
    ),
    (
        "Which problems does one subject have?",
        """SELECT rule, severity, recording_id, observed
FROM issues
WHERE subject = 'sub-136'
ORDER BY severity, rule, recording_id
LIMIT 6""",
    ),
    (
        "How many runs have no error-level issue, by site?",
        CLEAN_RUNS.strip()
        + """
SELECT r.acquisition AS site,
       count(*) AS runs_without_errors
FROM recordings r
LEFT JOIN problem_runs b USING (recording_id)
WHERE r.task = 'tmseeg' AND b.recording_id IS NULL
GROUP BY site
ORDER BY site""",
    ),
    (
        "Which runs can I use for a parietal analysis, with age and n-back accuracy?",
        CLEAN_RUNS.strip()
        + """
SELECT r.subject, p.age, p.sex,
       round(b.nback_accuracy, 3) AS nback_accuracy,
       r.has_signal
FROM recordings r
JOIN participants p USING (subject)
JOIN behavior b USING (subject)
LEFT JOIN problem_runs x USING (recording_id)
WHERE r.acquisition = 'parietal' AND x.recording_id IS NULL
  AND r.pulse_count = 120 AND b.nback_accuracy IS NOT NULL
ORDER BY r.has_signal DESC, r.subject
LIMIT 5""",
    ),
    (
        "How much of the release is on this machine?",
        """SELECT local,
       count(*) AS files,
       round(sum(size_bytes) / 1e9, 2) AS gigabytes
FROM files
GROUP BY local
ORDER BY local""",
    ),
]


def main() -> None:
    catalog = default_path(resolve_data_root())
    document = [
        "# Example catalog queries",
        "",
        "Generated by `scripts/catalog_queries.py` from ds008037 v1.0.1 on the build machine, so",
        "`has_signal` and `local` reflect that machine's downloads. Build the catalog first, then",
        "run the checks to fill the `issues` table:",
        "",
        "```bash",
        "uv run tmseeg-access catalog",
        "```",
        "",
        "```bash",
        "uv run tmseeg-access check",
        "```",
        "",
        "Run a query from the command line:",
        "",
        "```bash",
        'uv run tmseeg-access query "SELECT count(*) FROM recordings"',
        "```",
        "",
        "Tables: `recordings`, `participants`, `behavior`, `pulses`, `files`, `issues`.",
        "",
    ]
    timings = []
    for number, (question, sql) in enumerate(QUERIES, start=1):
        table = query(catalog, sql)
        durations = []
        for _ in range(REPEATS):
            started = time.perf_counter()
            query(catalog, sql)
            durations.append(time.perf_counter() - started)
        milliseconds = round(statistics.median(durations) * 1000, 1)
        timings.append({"question": question, "rows": len(table), "median_ms": milliseconds})
        document += [
            f"## {number}. {question}",
            "",
            "```sql",
            sql,
            "```",
            "",
            table.to_markdown(index=False) if len(table) else "No rows.",
            "",
        ]
    (ROOT / "docs" / "catalog_queries.md").write_text("\n".join(document), encoding="utf-8")
    result = {
        "queries": timings,
        "repeats_each": REPEATS,
        "slowest_median_ms": max(t["median_ms"] for t in timings),
        "note": "Each timing includes opening the catalog file, read from the E: drive.",
    }
    (ROOT / "results" / "catalog_queries.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
